/** 城市名 → Boss 城市码；未收录返回 undefined（调用方降级处理）。 */
export function cityToCode(city: string): string | undefined {
  const normalized = city.replace(/[市省]$/g, '').trim();
  return CITY_CODES[normalized];
}

/** 已收录的城市名列表（设置/提示用）。 */
export function knownCities(): string[] {
  return Object.keys(CITY_CODES);
}
